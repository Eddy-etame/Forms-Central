/**
 * Regenerate lib/agentDocs.ts from the markdown sources in docs/agent/.
 *
 *   node scripts/build-agent-docs.mjs
 *
 * The markdown is the thing collaborators edit; the TypeScript module is what
 * the /inlet-skill.md and /llm-install.md routes serve. JSON-escaping keeps the
 * code fences (backticks, ${…}) literal inside the TS string.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const skill = readFileSync(new URL('../docs/agent/inlet-skill.md', import.meta.url), 'utf8');
const install = readFileSync(new URL('../docs/agent/llm-install.md', import.meta.url), 'utf8');

const out = `// GENERATED by scripts/build-agent-docs.mjs — edit docs/agent/*.md, then re-run it.
// Raw markdown for the agent docs, JSON-escaped so code samples (backticks,
// \${…}) stay literal. Served by /inlet-skill.md and /llm-install.md.

export const INLET_SKILL_MD = ${JSON.stringify(skill)};

export const LLM_INSTALL_MD = ${JSON.stringify(install)};
`;
writeFileSync(new URL('../lib/agentDocs.ts', import.meta.url), out);
console.log(`✓ lib/agentDocs.ts regenerated (${skill.length + install.length} chars)`);
